// pbVarint and pbBytes write one field of the protobuf binary encoding.
func pbVarint(number, value int) []byte {
	return append(pbUvarint(uint64(number)<<3), pbUvarint(uint64(value))...)
}

func pbBytes(number int, body ...[]byte) []byte {
	joined := slices.Concat(body...)
	return slices.Concat(pbUvarint(uint64(number)<<3|2), pbUvarint(uint64(len(joined))), joined)
}

func pbString(number int, s string) []byte { return pbBytes(number, []byte(s)) }

func pbUvarint(v uint64) []byte {
	var b []byte
	for v >= 0x80 {
		b = append(b, byte(v)|0x80)
		v >>= 7
	}
	return append(b, byte(v))
}

// pingDescriptor is v1/ping.proto: enum Status, message PingRequest with the
// field number and the group Result, whose field is value.
func pingDescriptor() []byte {
	return slices.Concat(
		pbString(1, "v1/ping.proto"),
		pbString(2, "v1"),
		pbBytes(4,
			pbString(1, "PingRequest"),
			pbBytes(2, pbString(1, "number"), pbVarint(3, 1)),
			pbBytes(2, pbString(1, "result"), pbVarint(3, 2)),
			pbBytes(3, pbString(1, "Result"), pbBytes(2, pbString(1, "value"), pbVarint(3, 1))),
		),
		pbBytes(5, pbString(1, "Status"),
			pbBytes(2, pbString(1, "STATUS_UNSPECIFIED"), pbVarint(2, 0)),
			pbBytes(2, pbString(1, "STATUS_OK"), pbVarint(2, 1))),
	)
}

func byteLiteral(b []byte) string {
	words := make([]string, len(b))
	for i, c := range b {
		words[i] = fmt.Sprintf("0x%02x", c)
	}
	return "[]byte{" + strings.Join(words, ", ") + "}"
}

// protobufModule is a target whose gen/v1/ping.pb.go is protoc-gen-go output
// spelling its descriptor as rawDesc, beside protoc-gen-go-grpc and
// protoc-gen-connect-go output for the same file and a gogo file, each runtime a
// stub module the target replaces.
func protobufModule(t *testing.T, rawDesc string) string {
	t.Helper()
	pb := "// Code generated by protoc-gen-go. DO NOT EDIT.\n// versions:\n// \tprotoc-gen-go v1.36.5\n// \tprotoc        v5.29.3\n" +
		"// source: v1/ping.proto\n\npackage v1\n\nimport protoimpl \"google.golang.org/protobuf/runtime/protoimpl\"\n\n" +
		"type Status int32\n\nconst (\n\tStatus_STATUS_UNSPECIFIED Status = 0\n\tStatus_STATUS_OK Status = 1\n)\n\n" +
		"type PingRequest struct {\n\tstate protoimpl.MessageState\n\tNumber int32 `protobuf:\"varint,1,opt,name=number,proto3\"`\n" +
		"\tResult *PingRequest_Result `protobuf:\"group,2,opt,name=Result\"`\n}\n\n" +
		"func (x *PingRequest) GetNumber() int32 {\n\tif x != nil {\n\t\treturn x.Number\n\t}\n\treturn 0\n}\n\n" +
		"type PingRequest_Result struct {\n\tValue int32 `protobuf:\"varint,1,opt,name=value\"`\n}\n\n" +
		rawDesc + "\n\n" +
		"var file_v1_ping_proto_goTypes = []any{\n\t(Status)(0), // 0: v1.Status\n\t(*PingRequest)(nil), // 1: v1.PingRequest\n" +
		"\t(*PingRequest_Result)(nil), // 2: v1.PingRequest.Result\n}\n"
	grpc := "// Code generated by protoc-gen-go-grpc. DO NOT EDIT.\n// versions:\n// - protoc-gen-go-grpc v1.5.1\n// - protoc             v5.29.3\n" +
		"// source: v1/ping.proto\n\npackage v1\n\nconst PingService_Ping_FullMethodName = \"/v1.PingService/Ping\"\n\n" +
		"type PingServiceClient interface {\n\tPing(in *PingRequest) (*PingRequest, error)\n}\n\n" +
		"type pingServiceClient struct{}\n\nfunc NewPingServiceClient() PingServiceClient { return pingServiceClient{} }\n\n" +
		"func (pingServiceClient) Ping(in *PingRequest) (*PingRequest, error) { return in, nil }\n\n" +
		"type PingServiceServer interface {\n\tPing(*PingRequest) (*PingRequest, error)\n}\n"
	connect := "// Code generated by protoc-gen-connect-go. DO NOT EDIT.\n//\n// Source: v1/ping.proto\n\npackage v1connect\n\n" +
		"import (\n\tconnect \"connectrpc.com/connect\"\n\tv1 \"example.com/app/gen/v1\"\n)\n\n" +
		"const PingServicePingProcedure = \"/v1.PingService/Ping\"\n\n" +
		"type PingServiceClient interface {\n\tPing(*connect.Request[v1.PingRequest]) error\n}\n"
	return writeModule(t, map[string]string{
		"go.mod": "module example.com/app\n\ngo 1.27.1\n\nrequire (\n\tconnectrpc.com/connect v1.18.1\n\tgoogle.golang.org/protobuf v1.36.5\n)\n\n" +
			"replace connectrpc.com/connect => ./stub/connect\n\nreplace google.golang.org/protobuf => ./stub/protobuf\n",
		"main.go":                              "package main\n\nimport v1 \"example.com/app/gen/v1\"\n\nfunc main() { _ = v1.PingRequest{} }\n",
		"gen/v1/ping.pb.go":                    pb,
		"gen/v1/ping_grpc.pb.go":               grpc,
		"gen/v1/v1connect/ping.connect.go":     connect,
		"gen/old/old.pb.go":                    "// Code generated by protoc-gen-gogo. DO NOT EDIT.\n// source: old/old.proto\n\npackage old\n\ntype Old struct{}\n",
		"stub/protobuf/go.mod":                 "module google.golang.org/protobuf\n\ngo 1.27.1\n",
		"stub/protobuf/runtime/protoimpl/x.go": "package protoimpl\n\ntype MessageState struct{}\n",
		"stub/connect/go.mod":                  "module connectrpc.com/connect\n\ngo 1.27.1\n",
		"stub/connect/connect.go":              "package connect\n\ntype Request[T any] struct{ Msg *T }\n",
		repositoryDocument:                     `{"target": {"kind": "application"}}`,
	})
}

// bindingLines is every binding record of a facts document as one line.
func bindingLines(facts map[string]any) []string {
	var lines []string
	for _, entry := range facts["bindings"].([]any) {
		b := entry.(map[string]any)
		line := fmt.Sprint(b["role"], " ", b["symbol"], " ", b["schema"], " ", b["schema_file"], " ", b["generated_file"])
		if scope, ok := b["scope"]; ok {
			line += " " + scope.(string)
		}
		lines = append(lines, line)
	}
	slices.Sort(lines)
	return lines
}

// The protoc-gen-go file binds every message, field, getter, enum and value through
// its descriptor, whichever of the three spellings holds it; a group field binds by
// its number, not by the message name its tag carries; the gRPC and Connect files
// bind their service and RPC and publish no fallback; the gogo file is a fallback.
func TestFactsBindEveryGeneratedDeclarationToItsSchemaDeclaration(t *testing.T) {
	desc := pingDescriptor()
	shapes := map[string]string{
		"a-byte-slice":        "var file_v1_ping_proto_rawDesc = " + byteLiteral(desc),
		"a-string-conversion": "var file_v1_ping_proto_rawDesc = string(" + byteLiteral(desc) + ")",
		"a-string-constant":   "const file_v1_ping_proto_rawDesc = " + strconv.Quote(string(desc)),
	}
	const (
		pkg     = "go://example.com/app/gen/v1#"
		connect = "go://example.com/app/gen/v1/v1connect#"
		pbFile  = "gen/v1/ping.pb.go"
		rpcFile = "gen/v1/ping_grpc.pb.go"
		conFile = "gen/v1/v1connect/ping.connect.go"
		schema  = "v1/ping.proto"
	)
	consumer := func(symbol, ref, file string) string {
		return "consumer " + symbol + " proto://v1#" + ref + " " + schema + " " + file
	}
	want := []string{
		consumer(connect+"PingServiceClient", "PingService", conFile),
		consumer(connect+"PingServiceClient.Ping", "PingService.Ping", conFile),
		consumer(pkg+"NewPingServiceClient", "PingService", rpcFile),
		consumer(pkg+"PingRequest", "PingRequest", pbFile),
		consumer(pkg+"PingRequest.GetNumber", "PingRequest.number", pbFile),
		consumer(pkg+"PingRequest.Number", "PingRequest.number", pbFile),
		consumer(pkg+"PingRequest.Result", "PingRequest.result", pbFile),
		consumer(pkg+"PingRequest_Result", "PingRequest.Result", pbFile),
		consumer(pkg+"PingRequest_Result.Value", "PingRequest.Result.value", pbFile),
		consumer(pkg+"PingServiceClient", "PingService", rpcFile),
		consumer(pkg+"PingServiceClient.Ping", "PingService.Ping", rpcFile),
		consumer(pkg+"PingServiceServer", "PingService", rpcFile),
		consumer(pkg+"Status", "Status", pbFile),
		consumer(pkg+"Status_STATUS_OK", "Status.STATUS_OK", pbFile),
		consumer(pkg+"Status_STATUS_UNSPECIFIED", "Status.STATUS_UNSPECIFIED", pbFile),
		"fallback go://example.com/app/gen/old#old.pb.go:file <nil> old/old.proto gen/old/old.pb.go all",
	}
	slices.Sort(want)
	for name, raw := range shapes {
		t.Run(name, func(t *testing.T) {
			facts, _ := analyzeWithFacts(t, protobufModule(t, raw))
			if got := bindingLines(facts); !slices.Equal(got, want) {
				t.Errorf("the bindings are\n%s\nwant\n%s", strings.Join(got, "\n"), strings.Join(want, "\n"))
			}
			rows := make(map[string]any)
			for _, entry := range facts["generated"].([]any) {
				g := entry.(map[string]any)
				rows[g["path"].(string)] = g["generator"]
			}
			if g, _ := rows[pbFile].(map[string]any); g["row"] != "protoc-gen-go-1" || g["version"] != "v1.36.5" {
				t.Errorf("%s names the generator %v, want protoc-gen-go-1 at v1.36.5", pbFile, rows[pbFile])
			}
			if g, _ := rows[conFile].(map[string]any); g["row"] != "protoc-gen-connect-go-1" {
				t.Errorf("%s names the generator %v, want protoc-gen-connect-go-1", conFile, rows[conFile])
			}
		})
	}
}

func TestFactsBindAPlatformAlternativeOnceThroughItsLowestGeneratedFile(t *testing.T) {
	const (
		linux   = `{"id":"linux-amd64","os":"linux","arch":"amd64"}`
		windows = `{"id":"windows-amd64","os":"windows","arch":"amd64"}`
	)
	written := make(map[string][]byte)
	for order, configurations := range map[string]string{"linux-first": linux + "," + windows, "windows-first": windows + "," + linux} {
		dir := protobufModule(t, "var file_v1_ping_proto_rawDesc = "+byteLiteral(pingDescriptor()))
		original := filepath.Join(dir, "gen/v1/ping.pb.go")
		body, err := os.ReadFile(original)
		if err != nil {
			t.Fatal(err)
		}
		if err := os.Remove(original); err != nil {
			t.Fatal(err)
		}
		for _, goos := range []string{"linux", "windows"} {
			tagged := strings.Replace(string(body), "\n\npackage v1", "\n\n//go:build "+goos+"\n\npackage v1", 1)
			if err := os.WriteFile(filepath.Join(dir, "gen/v1/ping_"+goos+".pb.go"), []byte(tagged), 0o600); err != nil {
				t.Fatal(err)
			}
		}
		writeDocument(t, dir, repositoryDocument, `{"target":{"kind":"application"},"analysis":{"configurations":[`+configurations+`]}}`)
		factsPath := filepath.Join(t.TempDir(), "facts.json")
		if got := runAnalyze(t, dir, "--facts="+factsPath); got.code == vocab.ExitUsage || got.code == vocab.ExitFailure {
			t.Fatalf("%s: analyze --facts = %d, want a verdict\nstderr:\n%s", order, got.code, got.stderr)
		}
		if written[order], err = os.ReadFile(factsPath); err != nil {
			t.Fatalf("%s: analyze --facts wrote no facts document: %v", order, err)
		}
	}
	if !bytes.Equal(written["linux-first"], written["windows-first"]) {
		t.Errorf("the facts documents differ by configuration order:\nlinux first:\n%s\nwindows first:\n%s", written["linux-first"], written["windows-first"])
	}
	var facts map[string]any
	if err := json.Unmarshal(written["linux-first"], &facts); err != nil {
		t.Fatalf("decode the facts document: %v", err)
	}
	const request = "consumer go://example.com/app/gen/v1#PingRequest proto://v1#PingRequest v1/ping.proto gen/v1/ping_linux.pb.go"
	if got := bindingLines(facts); !slices.Contains(got, request) {
		t.Errorf("the bindings are\n%s\nwant one holding\n%s", strings.Join(got, "\n"), request)
	}
}
