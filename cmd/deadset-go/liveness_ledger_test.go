// linuxAndWindows is the repository configuration of an application built for two
// operating systems.
const linuxAndWindows = `{"target": {"kind": "application"}, "analysis": {"configurations": [` +
	`{"id": "linux-amd64", "os": "linux", "arch": "amd64", "tags": []},` +
	`{"id": "windows-amd64", "os": "windows", "arch": "amd64", "tags": []}]}}`

func TestATestOneConfigurationCompilesOfADeclarationAnotherKeepsLiveIsNoTestOfDeadCode(t *testing.T) {
	dir := writeModule(t, map[string]string{
		"go.mod":          "module example.com/app\n\ngo 1.27.1\n",
		"app.go":          "package main\n\nfunc main() {}\n\nfunc helper() int { return 1 }\n",
		"caller_linux.go": "package main\n\nfunc init() { _ = helper() }\n",
		"helper_windows_test.go": "package main\n\nimport \"testing\"\n\n" +
			"func TestHelper(t *testing.T) {\n\tif helper() != 1 {\n\t\tt.Fatal(\"helper\")\n\t}\n}\n",
		repositoryDocument: linuxAndWindows,
	})

	set := findingsOfDir(t, dir)
	for _, found := range slices.Concat(set.Result.Findings, set.Result.Withheld) {
		if found.Symbol.Ref == "go://example.com/app#TestHelper" {
			t.Errorf("the run reports TestHelper as %s, want nothing: the Linux build keeps helper live", found.Code)
		}
	}
}

