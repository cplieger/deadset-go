func TestExplainFollowsAPathThroughTheConfigurationsThatMakeEachHop(t *testing.T) {
	dir := writeModule(t, map[string]string{
		"go.mod":           "module example.com/app\n\ngo 1.27.1\n",
		"app.go":           "package main\n\nfunc main() {}\n\nfunc d() { work() }\n\nfunc s() {}\n",
		"work_linux.go":    "package main\n\nfunc init() { d() }\n\nfunc work() {}\n",
		"work_windows.go":  "package main\n\nfunc work() { s() }\n",
		repositoryDocument: linuxAndWindows,
	})

	got := runExplain(t, dir, "go://example.com/app#s")
	for _, want := range []string{
		"answer: live\n",
		"  reached from: root init work_linux.go:3:6\n",
		"  reference: work_linux.go:3:15\tcall\twork_linux.go:3:6 -> app.go:5:6\tin linux-amd64\n",
		"  reference: app.go:5:12\tcall\tapp.go:5:6 -> work_windows.go:3:6\tin windows-amd64\n",
		"  reference: work_windows.go:3:15\tcall\twork_windows.go:3:6 -> app.go:7:6\tin windows-amd64\n",
	} {
		if !strings.Contains(got.stdout, want) {
			t.Errorf("explain s =\n%s\nwant it to contain %q", got.stdout, want)
		}
	}
}

func TestExplainNamesNoConfigurationForAHopEveryConfigurationMakesThroughItsOwnWrite(t *testing.T) {
	// The write in main stores into a different x in each configuration, and the
	// Windows build alone calls w.
	dir := writeModule(t, map[string]string{
		"go.mod":           "module example.com/app\n\ngo 1.27.1\n",
		"app.go":           "package main\n\ntype T struct{ F func() }\n\nfunc helper() {}\n\nfunc main() { x = T{F: helper} }\n\nfunc w() {}\n",
		"x_linux.go":       "package main\n\nvar x T\n",
		"x_windows.go":     "package main\n\nvar x T\n\nfunc init() { x.F(); w() }\n",
		repositoryDocument: linuxAndWindows,
	})

	for symbol, want := range map[string]string{
		"helper": "  reference: app.go:7:24\tread\tapp.go:7:6 -> app.go:5:6\n",
		"w":      "  reference: x_windows.go:5:22\tcall\tx_windows.go:5:6 -> app.go:9:6\tin windows-amd64\n",
	} {
		if got := runExplain(t, dir, "go://example.com/app#"+symbol); !strings.Contains(got.stdout, want) {
			t.Errorf("explain %s =\n%s\nwant it to contain %q", symbol, got.stdout, want)
		}
	}
}

func TestExplainNamesTheMarkOrExemptionWhereAHeldSymbolsPathBegins(t *testing.T) {
	for _, tc := range []struct {
		name, app, gen, symbol string
		library                bool
		want                   []string
	}{
		{
			name: "mark",
			app: "package main\n\nfunc main() {}\n\n//deadset:ignore DS1002 -- kept for a later release.\n" +
				"func kept() { held() }\n\nfunc held() {}\n",
			symbol: "go://example.com/app#held",
			want: []string{
				"answer: live\n",
				"  reached from: suppression of app.go:6:6\n",
				"  reference: app.go:6:15\tcall\tapp.go:6:6 -> app.go:8:6\n",
			},
		},
		{
			name: "exemption",
			app: "package main\n\nimport (\n\t\"io\"\n\t\"strings\"\n)\n\n" +
				"func main() {\n\tvar s sink\n\tif _, err := io.Copy(&s, strings.NewReader(\"x\")); err != nil {\n\t\tpanic(err)\n\t}\n}\n\n" +
				"type sink struct{ n int }\n\n" +
				"func (s *sink) Write(p []byte) (int, error) {\n\ts.n += size(p)\n\treturn len(p), nil\n}\n\n" +
				"func size(p []byte) int { return len(p) }\n",
			symbol: "go://example.com/app#size",
			want: []string{
				"answer: live\n",
				"  reached from: root main app.go:8:6\n",
				"  use: exemption interface-satisfaction\tapp.go:8:6 -> app.go:17:16\n",
				"  reference: app.go:18:9\tcall\tapp.go:17:16 -> app.go:22:6\n",
			},
		},
		{
			name:   "exemption seed",
			app:    "package main\n\nfunc main() {}\n\nfunc helper() {}\n",
			gen:    "// Code generated by gen. DO NOT EDIT.\n\npackage main\n\nfunc Gen() { helper() }\n",
			symbol: "go://example.com/app#helper",
			want: []string{
				"answer: live\n",
				"  reached from: exemption generated-file of gen.go:5:6\n",
				"  reference: gen.go:5:14\tcall\tgen.go:5:6 -> app.go:5:6\n",
			},
		},
		{
			name: "inferred use",
			app: "package app\n\n// Speaker speaks.\ntype Speaker interface{ Speak() }\n\ntype dog struct{}\n\n" +
				"func (dog) Speak() { helper() }\n\nfunc helper() {}\n\n// New returns a Speaker.\nfunc New() Speaker { return dog{} }\n",
			library: true,
			symbol:  "go://example.com/app#helper",
			want: []string{
				"answer: live\n",
				"  reached from: root published-api app.go:4:25\n",
				"  use: inferred\tapp.go:4:25 -> app.go:8:12\n",
				"  reference: app.go:8:22\tcall\tapp.go:8:12 -> app.go:10:6\n",
			},
		},
	} {
		t.Run(tc.name, func(t *testing.T) {
			kind := "application"
			if tc.library {
				kind = "library"
			}
			files := map[string]string{
				"go.mod":           "module example.com/app\n\ngo 1.27.1\n",
				"app.go":           tc.app,
				repositoryDocument: `{"target": {"kind": "` + kind + `"}}`,
			}
			if tc.gen != "" {
				files["gen.go"] = tc.gen
			}
			dir := writeModule(t, files)
			got := runExplain(t, dir, tc.symbol)
			for _, want := range tc.want {
				if !strings.Contains(got.stdout, want) {
					t.Errorf("explain %s =\n%s\nwant it to contain %q", tc.symbol, got.stdout, want)
				}
			}
			if strings.Contains(got.stdout, "unreachable") {
				t.Errorf("explain %s =\n%s\nwant no unreachable line for a symbol the sweep holds live", tc.symbol, got.stdout)
			}
		})
	}
}
