// reportedOrWithheld is the one finding of a run, reported or withheld by the
// minimum confidence, whose subject is ref.
func reportedOrWithheld(t *testing.T, dir, ref string) *kinds.Finding {
	t.Helper()

	set := findingsOfDir(t, dir)
	for _, found := range slices.Concat(set.Result.Findings, set.Result.Withheld) {
		if found.Symbol.Ref == ref {
			return &found
		}
	}
	t.Fatalf("Setup: the run produces no finding about %s", ref)
	return nil
}

func TestATestOfAPossibleDeclarationIsNoTestOfDeadCodeAndLeavesItsComponent(t *testing.T) {
	dir := writeModule(t, map[string]string{
		"go.mod": "module example.com/lib\n\ngo 1.27.1\n",
		"lib.go": "package lib\n\n// Helper is published API only a test calls.\nfunc Helper() int { return 1 }\n",
		"lib_test.go": "package lib\n\nimport \"testing\"\n\n" +
			"func TestHelper(t *testing.T) {\n\tif Helper() != 1 {\n\t\tt.Fatal(\"helper\")\n\t}\n}\n",
		repositoryDocument: `{"target": {"kind": "library"}}`,
	})

	found := reportedOrWithheld(t, dir, "go://example.com/lib#Helper")
	if found.Code != vocab.TestOnlyUse || found.Component.SymbolCount != 1 {
		t.Errorf("Helper is %s in a component of %d symbols, want %s alone: outside programs may call it, so its test is no test of dead code",
			found.Code, found.Component.SymbolCount, vocab.TestOnlyUse)
	}
	if got := runExplain(t, dir, "go://example.com/lib#TestHelper"); !strings.Contains(got.stdout, "answer: live\n") {
		t.Errorf("explain TestHelper =\n%s\nwant answer: live", got.stdout)
	}
}

func TestATypeAnAnnotationSharesWithALiveDeclarationDoesNotFallWithTheWriteOnlyOne(t *testing.T) {
	dir := writeModule(t, map[string]string{
		"go.mod": "module example.com/app\n\ngo 1.27.1\n",
		"app.go": "package main\n\ntype box struct{ n int }\n\nvar x, y box\n\n" +
			"func main() {\n\tx = box{}\n\tprintln(y.n)\n}\n",
		repositoryDocument: `{"target": {"kind": "application"}}`,
	})

	found := reportedOrWithheld(t, dir, "go://example.com/app#x")
	if want := "variable x is written once and never read"; found.Message != want {
		t.Errorf("x's message is %q, want %q: deleting x leaves var y box", found.Message, want)
	}
}

func TestADeclarationOnlyAWriteInsideAWriteOnlySubjectsWriteNamesFallsWithTheSubject(t *testing.T) {
	dir := writeModule(t, map[string]string{
		"go.mod": "module example.com/app\n\ngo 1.27.1\n",
		"app.go": "package main\n\ntype T struct{ F func() }\n\nfunc helper() {}\n\nvar x T\n\n" +
			"func main() {\n\tx = T{F: helper}\n\tt := T{F: func() {}}\n\tt.F()\n}\n",
		repositoryDocument: `{"target": {"kind": "application"}}`,
	})

	found := reportedOrWithheld(t, dir, "go://example.com/app#x")
	if want := "variable x is written once and never read, and deleting it with its writes also deletes function helper"; found.Message != want {
		t.Errorf("x's message is %q, want %q: deleting x's only write deletes the only reference to helper", found.Message, want)
	}
}

func TestADeclarationNestedWriteOnlySubjectsWritesCarryFallsWithTheInnermostSubject(t *testing.T) {
	dir := writeModule(t, map[string]string{
		"go.mod":           "module example.com/app\n\ngo 1.27.1\n",
		"app.go":           "package main\n\ntype T struct{ F func() }\n\nfunc helper() {}\n\nvar x T\n\nfunc main() { x = T{F: helper} }\n",
		repositoryDocument: `{"target": {"kind": "application"}}`,
	})

	for ref, want := range map[string]string{
		"go://example.com/app#T.F": "field T.F is written once and never read, and deleting it with its writes also deletes function helper",
		"go://example.com/app#x":   "variable x is written once and never read, and deleting it with its writes also deletes type T",
	} {
		if found := reportedOrWithheld(t, dir, ref); found.Message != want {
			t.Errorf("%s's message is %q, want %q: helper's one reference is in T.F's write, inside x's", ref, found.Message, want)
		}
	}
}

